import asyncio
import json
import os
import secrets
import string
import time
from typing import Dict, Optional
from urllib.error import HTTPError
from urllib.request import Request, urlopen

import psutil
from patchright.async_api import async_playwright

from config.settings import settings
from engines.playwright_base import PlaywrightBase
from utils.js_script import load_js_script
from utils.process import find_new_child_processes

REMOTE_API_URL = "https://dolphin-anty-api.com"


class DolphinAntyEngine(PlaywrightBase):
    def __init__(
            self,
            name: str = "dolphin_anty",
            api_token: str = "",
            local_api_url: str = "http://localhost:3001",
            browser_version: int = 158,
            headless: bool = False,
            proxy: Optional[Dict[str, str]] = None,
            **kwargs
    ):
        """
        Initialize the DolphinAntyEngine with the given parameters

        Every start creates a fresh Windows profile (fingerprint generated by Dolphin, timezone/language/geolocation
        following the proxy), launches it through the local API and deletes exactly that profile on stop.
        Requires the Dolphin Anty app running with its local API, and a plan that includes API access.

        :param name: Name of the engine instance
        :param api_token: Dolphin Anty API token
        :param local_api_url: Local API of the running Dolphin Anty app
        :param browser_version: Major version of the Chromium build Dolphin Anty runs (the user agent must match it)
        :param headless: Whether to run the browser in headless mode
        :param proxy: Proxy settings, if any
        """

        super().__init__(name, "chromium", None, headless, proxy)
        self._api_token = api_token
        self._local_api_url = local_api_url.rstrip("/")
        self._browser_version = browser_version
        self._profile_id: Optional[int] = None

    @property
    def supported_proxy_protocols(self) -> list[str]:
        return ["http", "socks5"]

    def _call(self, method: str, url: str, body: Optional[dict] = None, auth: bool = True) -> dict:
        """Make a request to the Dolphin Anty cloud (auth=True) or local API"""

        headers = {"Content-Type": "application/json"}
        if auth:
            headers["Authorization"] = f"Bearer {self._api_token}"
        data = json.dumps(body).encode("utf-8") if body is not None else None
        try:
            with urlopen(Request(url, data=data, method=method, headers=headers), timeout=60) as resp:
                return json.loads(resp.read() or b"{}")
        except HTTPError as e:
            raise RuntimeError(f"Dolphin Anty API {method} {url.split('?')[0]} failed: {e.code} {e.read()[:300]!r}")

    def _create_profile(self) -> int:
        """Create a fresh profile for this run and return its ID"""

        fingerprint = self._call(
            "GET", f"{REMOTE_API_URL}/fingerprints/fingerprint?platform=windows&browser_type=anty"
                   f"&browser_version={self._browser_version}&type=fingerprint&screen=1920x1080"
        )
        suffix = "".join(secrets.choice(string.ascii_lowercase + string.digits) for _ in range(6))
        name = f"benchmark-{self.name}-{suffix}"
        profile = {
            "name": name,
            "tags": ["benchmark"],
            "browserType": "anty",
            "mainWebsite": "",
            "platform": "windows",
            "useragent": {"mode": "manual", "value": fingerprint["userAgent"]},
            "webrtc": {"mode": "altered", "ipAddress": None},
            "canvas": {"mode": "noise"},
            "webgl": {"mode": "noise"},
            "webglInfo": {
                "mode": "manual",
                "vendor": fingerprint["webgl"]["unmaskedVendor"],
                "renderer": fingerprint["webgl"]["unmaskedRenderer"],
                "webgl2Maximum": fingerprint.get("webgl2Maximum", {}),
            },
            "webgpu": {"mode": "real"},
            "clientRect": {"mode": "noise"},
            "timezone": {"mode": "auto", "value": None},
            "locale": {"mode": "auto", "value": None},
            "geolocation": {"mode": "auto", "latitude": None, "longitude": None, "accuracy": None},
            "cpu": {"mode": "manual", "value": 8},
            "memory": {"mode": "manual", "value": 8},
            "doNotTrack": False,
            "args": [],
        }
        if self.proxy:
            profile["proxy"] = {
                "type": self.proxy["protocol"],
                "host": self.proxy["host"],
                "port": str(self.proxy["port"]),
                "login": self.proxy.get("username", ""),
                "password": self.proxy.get("password", ""),
                "name": name,
            }

        response = self._call("POST", f"{REMOTE_API_URL}/browser_profiles", profile)
        if not response.get("browserProfileId"):
            raise RuntimeError(f"Dolphin Anty profile creation failed: {response}")
        return response["browserProfileId"]

    def _delete_profile(self, profile_id: int) -> None:
        """Delete the profile created by this engine (only that ID, without moving it to the trash)"""

        # retry: right after stop the profile may still be closing and the delete gets rejected
        for _ in range(5):
            try:
                response = self._call("DELETE", f"{REMOTE_API_URL}/browser_profiles?forceDelete=1", {"ids": [profile_id]})
                if response.get("success"):
                    return
            except Exception:
                pass
            time.sleep(2)

    async def start(self) -> None:
        """Create a Dolphin Anty profile, launch it, and connect via CDP"""

        self._start_time = asyncio.get_event_loop().time()

        parent_process = psutil.Process(os.getpid())
        process_children_before = parent_process.children(recursive=True)

        await asyncio.to_thread(self._call, "POST", f"{self._local_api_url}/v1.0/auth/login-with-token",
                                {"token": self._api_token}, False)
        self._profile_id = await asyncio.to_thread(self._create_profile)

        query = "automation=1" + ("&headless=true" if self.headless else "")
        started = await asyncio.to_thread(
            self._call, "GET", f"{self._local_api_url}/v1.0/browser_profiles/{self._profile_id}/start?{query}",
            None, False
        )
        automation = started.get("automation") or {}
        if not automation.get("port"):
            raise RuntimeError(f"Dolphin Anty failed to launch the profile: {started}")

        self.playwright = await async_playwright().start()
        self.browser = await self.playwright.chromium.connect_over_cdp(
            f"ws://127.0.0.1:{automation['port']}{automation['wsEndpoint']}"
        )
        self.context = self.browser.contexts[0]

        await self.context.add_init_script(await load_js_script('unlockShadowDom.js'))

        self.page = await self.context.new_page()
        self.page.set_default_timeout(settings.browser.action_timeout_s * 1000)
        self.page.set_default_navigation_timeout(settings.browser.page_load_timeout_s * 1000)

        engine_major = self.browser.version.split(".")[0]
        if engine_major != str(self._browser_version):
            raise RuntimeError(f"Dolphin Anty runs Chromium {engine_major}, but the fingerprint was generated for "
                               f"{self._browser_version}: set DOLPHIN_BROWSER_VERSION={engine_major}")

        process_children_after = parent_process.children(recursive=True)
        self.process_list = find_new_child_processes(process_children_before, process_children_after)

    async def stop(self) -> None:
        """Close page, disconnect browser, stop and delete the Dolphin Anty profile"""

        try:
            if self.page:
                await self.page.close()
        except:
            pass
        self.page = None

        try:
            if self.browser:
                await self.browser.close()
        except:
            pass
        self.browser = None
        self.context = None

        try:
            if self.playwright:
                await self.playwright.stop()
        except:
            pass
        self.playwright = None

        if self._profile_id:
            try:
                await asyncio.to_thread(
                    self._call, "GET", f"{self._local_api_url}/v1.0/browser_profiles/{self._profile_id}/stop", None, False
                )
            except:
                pass
            await asyncio.to_thread(self._delete_profile, self._profile_id)
            self._profile_id = None

        self.process_list = None
